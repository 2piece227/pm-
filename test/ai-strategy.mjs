import assert from 'node:assert/strict';
import {Battle,Teams,Dex} from '@pkmn/sim';
import {createTrainerAI,makeRng,runBattle} from '../src/engine/run-battle.js';
import {ownView} from '../src/ai/opponent-model.js';
import {predictSwitch,preservationValue,strategyWeight,followupValue} from '../src/ai/strategy.js';
import {analyseBattle} from '../src/engine/battle-analysis.js';
import {renderBattleAnalysis} from '../src/ui/battle-analysis.js';
const gen=Dex.forGen(9),stats={judge:20,ops:20,focus:20,know:20,mental:20};
const b=new Battle({formatid:'gen9customgame',seed:[1,2,3,4]});
b.setPlayer('p1',{name:'A',team:Teams.pack(Teams.import('Garchomp\n- Earthquake\n- Dragon Claw\n\nCharizard\n- Flamethrower'))});
b.setPlayer('p2',{name:'B',team:Teams.pack(Teams.import('Jolteon\n- Thunderbolt\n\nLandorus-Therian\n- Earthquake'))});
b.makeChoices('default','default');
const ai=createTrainerAI({name:'A',stats},'균형형',makeRng(4));
const unknown=ai.chooseAction(b,'p1');assert.equal(unknown.think.strategy.switchProbability,0);
b.log.push('|turn|3','|switch|p2a: Landorus|Landorus-Therian|100/100','|move|p2a: Landorus|Earthquake|p1a: Garchomp','|switch|p2a: Jolteon|Jolteon|70/100','|turn|5');b.turn=5;
const before=JSON.stringify(b.toJSON()),known=ai.chooseAction(b,'p1');assert.equal(JSON.stringify(b.toJSON()),before);
assert(known.think.strategy.switchProbability>0&&known.think.strategy.switchProbability<=.65);
assert.deepEqual(known.think.strategy.targets,['Landorus']);
assert.equal([...known.think.options].sort((a,b)=>b.score-a.score)[0].label,'Dragon Claw','cover the publicly seen Ground immunity');
const analysis=analyseBattle({log:['|turn|5','|move|p1a: Garchomp|Dragon Claw|p2a: Jolteon'],think:[{turn:5,side:'p1',think:{...known.think,selected:known.think.options.findIndex(o=>o.label==='Dragon Claw'),mentalReasons:['급소 피격']}}]});
const rendered=renderBattleAnalysis(analysis);assert(rendered.includes('확정 예측은 아닙니다'));assert(rendered.includes('급소 피격'));
console.log('public switch prediction',known.think.strategy,known.think.options.map(o=>[o.label,+o.score.toFixed(1),o.predictionAdjustment]));
const me=ownView(b.p1.active[0]),foe=ownView(b.p2.active[0]),bench=ownView(b.p2.pokemon[1]);
const prediction=predictSwitch(gen,me,foe,[bench]);assert(prediction.probability>0);
assert.equal(predictSwitch(gen,me,foe,[]).probability,0);
assert.equal(predictSwitch(gen,me,{...foe,volatiles:{lockedmove:{move:'outrage'}}},[bench]).probability,0);
assert.equal(predictSwitch(gen,me,foe,[{...bench,hp:1}]).probability,0);
assert(predictSwitch(gen,me,foe,[bench],{recentSwitch:true}).probability<prediction.probability);
assert.equal(preservationValue(gen,me,[],[foe]),0);
assert(preservationValue(gen,me,[ownView(b.p1.pokemon[1])],[foe])>0);
assert(Math.abs(followupValue(gen,me,foe,gen.moves.get('earthquake')))<=8);
assert(strategyWeight({...stats,ops:7},0)<strategyWeight(stats,0));

const shaken=createTrainerAI({name:'S',stats:{...stats,mental:8}},'균형형',makeRng(1));
const calm=createTrainerAI({name:'C',stats},'균형형',makeRng(1));
for(const t of [shaken,calm]){
 t.observeOutcome(['|-miss|p1a: A|p2a: B'],'p1');assert.equal(t.shock,0);
 t.observeOutcome(['|-miss|p1a: A|p2a: B'],'p1');assert.equal(t.shock,1);
 t.observeOutcome(['|-crit|p1a: A'],'p1');assert.equal(t.shock,2.5);
 t.observeOutcome(['|move|p1a: A|Tackle|p2a: B'],'p1');assert.equal(t.failureStreak,0);
}
assert(shaken.temperature(1)>calm.temperature(1));
assert(shaken.cognitiveStats().focus<shaken.stats.focus);assert.equal(calm.cognitiveStats().focus,calm.stats.focus);
assert(strategyWeight(shaken.stats,shaken.shock)<strategyWeight(shaken.stats,0));
for(let i=0;i<5;i++)shaken.endTurn(false);assert.equal(shaken.shock,0);
assert.equal(shaken.cognitiveStats().focus,shaken.stats.focus);
calm.reset();assert.equal(calm.failureStreak,0);assert.equal(calm.shock,0);
b.destroy();
const trial=()=>runBattle({trainerA:createTrainerAI({name:'A',stats},'균형형',makeRng(7)),trainerB:createTrainerAI({name:'B',stats},'균형형',makeRng(8)),teamA:'Starmie\n- Surf\n- Recover',teamB:'Blissey\n- Thunderbolt\n- Soft-Boiled',seed:90,collectThink:true});
// Wall-clock protocol timestamps are not seeded battle outcomes.
const deterministicResult=()=>{const r=trial();return {...r,log:r.log.filter(line=>!line.startsWith('|t:|'))};};
assert.deepEqual(deterministicResult(),deterministicResult());
console.log('PASS: only publicly seen switches, bounded probabilities/branches, traps/hazards, specialist preservation, limited reply, mental events/recovery and deterministic engine');
